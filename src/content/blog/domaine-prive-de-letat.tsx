// Article : Domaine privé de l'État — peut-on faire une immatriculation directe ?
//
// Répond à une question fréquente des acheteurs : la procédure d'immatriculation
// directe (réservée au domaine NATIONAL, cf. /blog/immatriculation-directe) ne
// s'applique PAS aux terrains de l'État. L'article explique la distinction des
// catégories de terres et la vraie voie d'accès : concession puis cession.
// -------------------------------------------------------------------------------------------------

export default function DomainePriveDeLEtatArticle() {
  return (
    <>
      <p>
        « Peut-on faire une <strong>immatriculation directe</strong> sur le{" "}
        <strong>domaine privé de l'État</strong> ? » La question revient souvent,
        et la réponse courte est <strong>non</strong>. L'immatriculation directe
        est réservée aux terres du <strong>domaine national</strong> ; sur le
        domaine privé de l'État, on n'obtient pas un titre en s'immatriculant
        soi-même : on doit d'abord se faire <strong>céder</strong> le terrain par
        l'État, le plus souvent à l'issue d'une <strong>concession</strong>.
      </p>

      <blockquote>
        Cadre légal : ordonnance n° 74-1 du 6 juillet 1974 (régime foncier) et
        ordonnance n° 74-2 du 6 juillet 1974 (domaine de l'État), complétées par le
        décret n° 76-167 du 27 avril 1976 fixant les modalités de gestion du
        domaine privé de l'État. Les barèmes et seuils de compétence ont été
        retouchés par des textes ultérieurs : faites toujours confirmer l'état du
        droit applicable par un notaire ou la Délégation des Domaines.
      </blockquote>

      <h2>D'abord, comprendre les trois grandes catégories de terres</h2>
      <p>
        Au Cameroun, tout terrain relève de l'un de ces trois régimes — et c'est ce
        régime qui détermine la procédure d'accès à la propriété :
      </p>
      <ul>
        <li>
          <strong>Le domaine national</strong> — les terres non immatriculées et
          non rattachées à l'État. C'est là, et seulement là, que joue
          l'<a href="/blog/immatriculation-directe">immatriculation directe</a>{" "}
          (pour une occupation mise en valeur) ou{" "}
          <a href="/blog/immatriculation-indirecte">indirecte</a> (terres
          coutumières).
        </li>
        <li>
          <strong>Le domaine public de l'État</strong> — routes, rivages, cours
          d'eau, ouvrages publics. Il est <strong>inaliénable et imprescriptible</strong> :
          on ne peut ni l'acheter, ni l'immatriculer à son nom. Tout au plus une
          occupation précaire et révocable (permis d'occupation).
        </li>
        <li>
          <strong>Le domaine privé de l'État</strong> — les biens dont l'État est
          propriétaire « comme un particulier » : terrains déjà immatriculés au nom
          de l'État, biens vacants et sans maître, successions en déshérence,
          terrains du domaine national de 2ᵉ catégorie incorporés au domaine de
          l'État. Ces biens-là, eux, <strong>sont aliénables</strong> — mais selon
          une procédure bien précise.
        </li>
      </ul>

      <h2>Pourquoi l'immatriculation directe ne s'applique pas</h2>
      <p>
        L'immatriculation directe sert à <strong>créer un premier titre</strong> sur
        une terre qui n'en a pas, au profit de celui qui l'occupe et la met en
        valeur. Or, sur le domaine privé de l'État, le titre <strong>existe déjà</strong>{" "}
        (ou est établi) au nom de l'État : il n'y a rien à « créer ». Le particulier
        ne peut donc pas s'immatriculer dessus ; il peut seulement obtenir que l'État
        lui <strong>transfère</strong> ce droit. Le titre du particulier sera alors{" "}
        <strong>dérivé</strong> de celui de l'État, par mutation — et non créé de
        toutes pièces.
      </p>

      <h2>La vraie voie : la concession, puis la cession</h2>
      <p>
        Pour devenir propriétaire d'un terrain du domaine privé de l'État, le
        parcours type est le suivant :
      </p>
      <ol>
        <li>
          <strong>Demande</strong> adressée à l'administration (préfet / ministre en
          charge des Domaines selon la superficie et l'usage), avec un plan et le
          projet de mise en valeur.
        </li>
        <li>
          <strong>Concession provisoire</strong> accordée par arrêté, assortie d'un{" "}
          <strong>cahier des charges</strong> : elle ne donne pas la propriété, mais
          le droit d'occuper et l'<strong>obligation de mettre en valeur</strong>{" "}
          dans un délai imparti (souvent 3 à 5 ans).
        </li>
        <li>
          <strong>Mise en valeur</strong> effective (constructions, plantations,
          exploitation) puis <strong>constat</strong> par une commission.
        </li>
        <li>
          <strong>Concession définitive</strong> une fois la mise en valeur reconnue
          suffisante.
        </li>
        <li>
          <strong>Cession</strong> et établissement du <strong>titre foncier</strong>{" "}
          au nom du concessionnaire, inscrit au livre foncier. C'est seulement ici
          que l'on devient véritablement propriétaire.
        </li>
      </ol>
      <p>
        Selon les cas, l'État peut aussi procéder à une <strong>cession directe</strong>{" "}
        (de gré à gré ou par adjudication), ou consentir un simple{" "}
        <strong>bail</strong> à celui qui souhaite occuper sans acquérir.
      </p>

      <h2>Concession provisoire ou définitive : ne pas confondre</h2>
      <p>
        C'est l'erreur la plus coûteuse. Une <strong>concession provisoire</strong>{" "}
        n'est <em>pas</em> un titre de propriété : elle est précaire, conditionnelle
        et révocable si le cahier des charges n'est pas respecté. Tant que la
        concession définitive et la cession ne sont pas intervenues, le terrain
        reste à l'État. N'achetez jamais « une concession provisoire » comme s'il
        s'agissait d'un <a href="/blog/titre-foncier">titre foncier</a>.
      </p>

      <h2>Ce qu'il faut vérifier avant de s'engager</h2>
      <ul>
        <li>
          <strong>La nature réelle du terrain</strong> : appartient-il vraiment au
          domaine privé de l'État, ou est-ce une terre du domaine national qu'un
          vendeur présente abusivement comme « terrain de l'État » ?
        </li>
        <li>
          <strong>L'existence et le stade de la concession</strong> : provisoire ou
          définitive ? Quel cahier des charges, quel délai de mise en valeur ?
        </li>
        <li>
          <strong>Le respect des obligations</strong> : une concession dont la mise
          en valeur n'a pas été faite dans les délais peut être retirée — vous
          rachèteriez un droit fragile.
        </li>
        <li>
          <strong>L'absence de litige</strong> avec des occupants ou des
          revendications coutumières antérieures à l'incorporation au domaine de
          l'État.
        </li>
      </ul>

      <h2>En résumé</h2>
      <p>
        Sur le <strong>domaine privé de l'État</strong>, on ne s'immatricule pas
        directement : on obtient le terrain par <strong>concession puis cession</strong>,
        et le titre foncier qui en résulte est dérivé de celui de l'État.
        L'immatriculation directe, elle, reste la voie du{" "}
        <a href="/blog/immatriculation-directe">domaine national</a>. Avant tout
        engagement, faites qualifier le régime du terrain et sécuriser la mutation
        par un <a href="/blog/role-du-notaire">notaire</a> — c'est la meilleure
        assurance contre un achat fragile.
      </p>
    </>
  );
}
